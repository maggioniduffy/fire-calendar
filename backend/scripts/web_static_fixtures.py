"""Build the SYNTHETIC static tree used by the web e2e of the static mode (SA7.2).

The same synthetic `harmonized` layer as `web_fixtures.py` (shorter period) is exported with the real
`firecal.stages.publish.export.export_static` for one synthetic province with two departments. The files land
in `web/e2e/fixtures/static/` and have the layout of the contract (`manifest.json`, `areas.json`, `areas/`,
`calendar/`, `stats/`, `cells/`, `export/`). `backend/tests/test_web_static_fixtures.py` regenerates them and
checks they equal the committed ones.

The numbers are invented (seeded); they are NOT FIRMS data, and the geometries are NOT real boundaries.
Usage: uv run python scripts/web_static_fixtures.py [OUT_DIR]
"""

import importlib.util
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from shapely.geometry import box

from firecal.io import enso
from firecal.stages.publish.areas import AreaDef
from firecal.stages.publish.export import PreloadedStore, export_static

HERE = Path(__file__).resolve().parent
OUT_DEFAULT = HERE.parents[1] / "web" / "e2e" / "fixtures" / "static"
YEARS = range(2011, 2015)  # 2011 estimated VIIRS-eq, 2012-2014 observed
GENERATED_AT = datetime(2026, 1, 1, tzinfo=UTC)
BOUNDARIES = {
    "source": "SYNTHETIC fixture, not real boundaries",
    "license": "synthetic, no real data",
    "attribution": "SYNTHETIC fixture",
    "url": None,
    "sha256": None,
}
# lon_min, lat_min, lon_max, lat_max: rectangles over the synthetic cells (-34.05..-30.05, -65.05..-62.05).
PROVINCE = box(-65.5, -34.5, -61.5, -29.5)
NORTH = box(-65.5, -32.0, -61.5, -29.5)
SOUTH = box(-65.5, -34.5, -61.5, -32.0)
AREAS = [
    AreaDef("p-cordoba", "province", "Córdoba (SYNTHETIC)", None, PROVINCE),
    AreaDef("d-cordoba-norte", "department", "Norte (SYNTHETIC)", "p-cordoba", NORTH),
    AreaDef("d-cordoba-sur", "department", "Sur (SYNTHETIC)", "p-cordoba", SOUTH),
]  # fmt: skip
README = """# Synthetic static fixtures (web e2e, static mode)

SYNTHETIC data: a tiny invented layer around Cordoba (seeded), NOT real FIRMS counts, and rectangles that
are NOT real boundaries. Never show these numbers as real. Generated by
`backend/scripts/web_static_fixtures.py` with the real static export (`firecal publish export`); do not
edit by hand.
`backend/tests/test_web_static_fixtures.py` fails when these files differ from a fresh run.
"""


def load_web_fixtures():
    spec = importlib.util.spec_from_file_location("web_fixtures", HERE / "web_fixtures.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def generate(out: Path) -> list[str]:
    """Write the tree into `out`; return the sorted relative paths written."""
    wf = load_web_fixtures()
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        wf.build_layer(Path(tmp), YEARS)
        oni = Path(tmp) / "enso" / "oni_monthly.parquet"
        wf.build_enso(oni)
        store = PreloadedStore(Path(tmp) / "harmonized")
        export_static(
            out, store, AREAS, enso.read_enso(oni), BOUNDARIES, workers=1, generated_at=GENERATED_AT,
            notes={"synthetic": True},
            # Synthetic fixtures must never pick up the real FIRMS detections from data/.
            include_detections=False,
        )  # fmt: skip
    (out / "README.md").write_text(README)
    return sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DEFAULT
    print("\n".join(generate(target)))
