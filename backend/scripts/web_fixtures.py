"""Build the SYNTHETIC API fixtures used by the web e2e tests (SA4.1).

A tiny synthetic `harmonized` layer around Cordoba is written to a temp dir, the real FastAPI app answers
the requests through `TestClient`, and the JSON bodies land in `web/e2e/fixtures/api/` together with
`index.json` (canonical request key -> file). `backend/tests/test_web_fixtures.py` regenerates them and checks
they equal the committed ones, so the mocked contract cannot drift from the backend.

The numbers are invented (seeded); they are NOT FIRMS data and must never be shown as real.
Usage: uv run python scripts/web_fixtures.py [OUT_DIR]
"""

import json
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from fastapi.testclient import TestClient

from firecal.api.app import create_app
from firecal.layers.manifest import LayerManifest
from firecal.stages.harmonize.regions import block_ids

SEED = 20260101
YEARS = range(2005, 2017)  # 2005 (VIIRS-eq estimated) .. 2016; VIIRS reported from 2012
VIIRS_FIRST_YEAR = 2012
PERIOD = "2005-01-01/2016-12-31"
SOURCE = "SYNTHETIC fixture, not real FIRMS data"
OUT_DEFAULT = Path(__file__).resolve().parents[2] / "web" / "e2e" / "fixtures" / "api"

# Cell centers are k*0.1 + 0.05: a coarse grid over the Cordoba preset plus a few cells near the city.
GRID_LAT = (-34.05, -33.05, -32.05, -31.05, -30.05)
GRID_LON = (-65.05, -64.05, -63.05, -62.05)
EXTRA = ((-31.45, -64.15), (-31.65, -64.35), (-31.25, -63.85), (-31.55, -64.25))

# "Geolocation" point used by the e2e (Cordoba city) and the polygon the fixture answers for.
GEO_POINT = (-31.42, -64.18)
GEO_RADIUS_KM = 230
POLYGON_COORDS = [[[-64.6, -32.0], [-63.6, -32.0], [-63.6, -31.0], [-64.6, -31.0], [-64.6, -32.0]]]

AREAS: dict[str, dict] = {
    "cordoba": {"preset": "cordoba"},
    "circle": {
        "area": {"type": "circle", "lat": GEO_POINT[0], "lon": GEO_POINT[1], "radius_km": GEO_RADIUS_KM}
    },
    "polygon": {"area": {"type": "polygon", "geojson": {"type": "Polygon", "coordinates": POLYGON_COORDS}}},
}
SCALES = ("viirs_eq", "modis_eq")
PATHS = ("/calendar", "/stats")
MONTHS = ("2016-12", "2005-09")  # latest month of the layer and one estimated (VIIRS-eq) month
DET_BBOX = [-35.0, -29.0, -66.0, -61.0]  # any view window: the synthetic server has no raw detections

README = """# Synthetic API fixtures (web e2e)

SYNTHETIC data: a tiny invented layer around Cordoba (seeded), NOT real FIRMS counts. Never show these numbers
as real. Generated by `backend/scripts/web_fixtures.py` through the real FastAPI app; do not edit by hand.
`backend/tests/test_web_fixtures.py` fails when these files differ from a fresh run.

`index.json` maps a canonical request key to a file; see `web/e2e/api.ts` for the key format. `/cells` is
keyed by month (the view window `bbox` is not part of the key, so the fixture holds every cell of the area).
`/detections` answers 404 (`statuses` in `index.json`): the synthetic server has no raw detections.
A polygon request (any vertices) maps to the one polygon fixture.
"""


def request_key(path: str, body: dict) -> str:
    """Canonical key of a request; must match `requestKey` in web/e2e/api.ts."""
    if "preset" in body:
        area = f"preset:{body['preset']}"
    elif body["area"]["type"] == "circle":
        a = body["area"]
        area = f"circle:{a['lat']:.2f},{a['lon']:.2f},{a['radius_km']:g}"
    else:
        area = "polygon"
    parts = [f"POST {path}", f"area={area}", f"scale={body.get('scale', 'viirs_eq')}"]
    for k in ("month", "start", "end", "ref"):
        if body.get(k):
            parts.append(f"{k}={body[k]}")
    return " ".join(parts)


def synthetic_rows() -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    cells = [(la, lo) for la in GRID_LAT for lo in GRID_LON] + list(EXTRA)
    rows = []
    for year in YEARS:
        for month in range(1, 13):
            season = 1.0 + 3.0 * np.exp(-(((month - 9) % 12) ** 2) / 6.0)  # peak around September
            trend = 1.0 + 0.05 * (year - YEARS[0])
            for i, (la, lo) in enumerate(cells):
                n = int(rng.poisson(0.6 * season * trend * (1.5 if i % 3 == 0 else 0.7)))
                if n == 0 and i != 0:
                    continue
                n = max(n, 1) if i == 0 else n  # every month keeps at least one row (sensor availability)
                viirs = year >= VIIRS_FIRST_YEAR
                vrep = float(rng.poisson(n * 1.8)) if viirs else np.nan
                rows.append(
                    {
                        "year": year, "month": month, "cell_id": int(abs(la) * 1000 + abs(lo) * 10),
                        "cell_lat": la, "cell_lon": lo,
                        "modis_reported": float(n), "viirs_reported": vrep,
                        "modis_eq": float(n), "viirs_eq": vrep if viirs else round(n * 1.8, 3),
                        "modis_eq_estimated": False, "viirs_eq_estimated": not viirs,
                        "modis_sats": "terra", "viirs_source": "snpp" if viirs else "",
                        "method": "synthetic", "calibration_version": "synthetic-1",
                    }
                )  # fmt: skip
    return pd.DataFrame(rows)


def bands(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    est = df[df["viirs_eq_estimated"]].copy()
    est["block"] = block_ids(est["cell_lat"].to_numpy(), est["cell_lon"].to_numpy())
    common = {"target": "viirs_eq", "nominal": 0.8}
    m = est.groupby(["year", "month", "block"], as_index=False)["viirs_eq"].sum()
    y = est.groupby(["year", "block"], as_index=False)["viirs_eq"].sum()
    out = []
    for g in (m, y):
        g = g.rename(columns={"viirs_eq": "estimate"})
        g["lo"], g["hi"] = (g["estimate"] * 0.7).round(3), (g["estimate"] * 1.4).round(3)
        out.append(g.assign(**common))
    return out[0], out[1]


def build_layer(processed: Path) -> None:
    root = processed / "harmonized"
    df = synthetic_rows()
    (root / "series").mkdir(parents=True)
    for year, g in df.groupby("year"):
        g.to_parquet(root / "series" / f"{year}.parquet")
    month, year = bands(df)
    for name, b in (("band_block_month", month), ("band_block_year", year)):
        (root / name).mkdir()
        for y, g in b.groupby("year"):
            g.to_parquet(root / name / f"{y}.parquet")
    manifest = LayerManifest(
        id="harmonized", title="Harmonized fire series (SYNTHETIC)", kind="series", source=SOURCE,
        period=PERIOD, license="synthetic, no real data", updated_at=datetime(2026, 1, 1, tzinfo=UTC),
        files=[f"series/{y}.parquet" for y in sorted(df["year"].unique())],
        method="synthetic", calibration_version="synthetic-1",
        notes={
            "es": ["Datos sintéticos de prueba: no son focos reales."],
            "en": ["Synthetic test data: not real hot spots."],
        },
    )  # fmt: skip
    (root / "manifest.json").write_text(manifest.model_dump_json())


def dump(obj) -> str:
    return json.dumps(obj, sort_keys=True, indent=1, ensure_ascii=False) + "\n"


def generate(out: Path) -> list[str]:
    """Write the fixtures into `out`; return the file names written."""
    out.mkdir(parents=True, exist_ok=True)
    index: dict[str, str] = {}
    statuses: dict[str, int] = {}
    with tempfile.TemporaryDirectory() as tmp:
        build_layer(Path(tmp))
        client = TestClient(create_app(processed_dir=Path(tmp), detections_dir=Path(tmp) / "no-detections"))
        for area_name, area_body in AREAS.items():
            for scale in SCALES:
                for path in PATHS:
                    body = {**area_body, "scale": scale}
                    resp = client.post(path, json=body)
                    resp.raise_for_status()
                    name = f"{path.strip('/')}-{area_name}-{scale}.json"
                    (out / name).write_text(dump(resp.json()))
                    index[request_key(path, body)] = name
                for month in MONTHS:
                    body = {**area_body, "scale": scale, "month": month}
                    resp = client.post("/cells", json=body)
                    resp.raise_for_status()
                    name = f"cells-{area_name}-{scale}-{month}.json"
                    (out / name).write_text(dump(resp.json()))
                    index[request_key("/cells", body)] = name
                    det = client.post("/detections", json={**body, "bbox": DET_BBOX})
                    assert det.status_code == 404, det.text
                    (out / "detections-404.json").write_text(dump(det.json()))
                    key = request_key("/detections", body)
                    index[key] = "detections-404.json"
                    statuses[key] = 404
    (out / "index.json").write_text(
        dump(
            {
                "synthetic": True,
                "note": "SYNTHETIC data, not real FIRMS counts",
                "requests": index,
                "statuses": statuses,
            }
        )
    )
    (out / "README.md").write_text(README)
    return sorted({*index.values(), "index.json", "README.md"})


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DEFAULT
    print("\n".join(generate(target)))
