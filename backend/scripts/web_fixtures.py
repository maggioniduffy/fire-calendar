"""Build the SYNTHETIC API fixtures used by the web e2e tests (SA4.1).

A tiny synthetic `harmonized` layer around Cordoba is written to a temp dir, the real FastAPI app answers
the requests through `TestClient`, and the JSON bodies land in `web/e2e/fixtures/api/` together with
`index.json` (canonical request key -> file). `backend/tests/test_web_fixtures.py` regenerates them and checks
they equal the committed ones, so the mocked contract cannot drift from the backend.

The numbers are invented (seeded); they are NOT FIRMS data and must never be shown as real.
Usage: uv run python scripts/web_fixtures.py [OUT_DIR]
"""

import json
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from fastapi.testclient import TestClient

from firecal.api.app import create_app
from firecal.io import enso
from firecal.layers.manifest import LayerManifest
from firecal.stages.harmonize.regions import block_ids

SEED = 20260101
YEARS = range(2005, 2017)  # 2005 (VIIRS-eq estimated) .. 2016; VIIRS reported from 2012
VIIRS_FIRST_YEAR = 2012
PERIOD = "2005-01-01/2016-12-31"
SOURCE = "SYNTHETIC fixture, not real FIRMS data"
OUT_DEFAULT = Path(__file__).resolve().parents[2] / "web" / "e2e" / "fixtures" / "api"

# Cell centers are k*0.1 + 0.05: a coarse grid over the Cordoba preset plus a few cells near the city.
GRID_LAT = (-34.05, -33.05, -32.05, -31.05, -30.05)
GRID_LON = (-65.05, -64.05, -63.05, -62.05)
EXTRA = ((-31.45, -64.15), (-31.65, -64.35), (-31.25, -63.85), (-31.55, -64.25))

# "Geolocation" point used by the e2e (Cordoba city) and the polygon the fixture answers for.
GEO_POINT = (-31.42, -64.18)
GEO_RADIUS_KM = 230
POLYGON_COORDS = [[[-64.6, -32.0], [-63.6, -32.0], [-63.6, -31.0], [-64.6, -31.0], [-64.6, -32.0]]]

AREAS: dict[str, dict] = {
    "cordoba": {"preset": "cordoba"},
    "circle": {
        "area": {"type": "circle", "lat": GEO_POINT[0], "lon": GEO_POINT[1], "radius_km": GEO_RADIUS_KM}
    },
    "polygon": {"area": {"type": "polygon", "geojson": {"type": "Polygon", "coordinates": POLYGON_COORDS}}},
}
SCALES = ("viirs_eq", "modis_eq")
PATHS = ("/calendar", "/stats")
MONTHS = tuple(f"{y}-{m:02d}" for y in YEARS for m in range(1, 13))  # every month of the fixture period
DETECTIONS_404 = "detections-404.json"
# Months the specs request outside the Cordoba VIIRS-eq calendar (which clicks any month): the default
# (latest),
# one estimated VIIRS-eq month and one observed month. Keeps the committed fixtures small.
KEY_MONTHS = ("2005-09", "2015-09", "2016-12")


def months_for(area_name: str, scale: str) -> tuple[str, ...]:
    """Every month for the calendar's area and scale; the months the specs request otherwise."""
    return MONTHS if (area_name, scale) == ("cordoba", "viirs_eq") else KEY_MONTHS


DET_BBOX = [-35.0, -29.0, -66.0, -61.0]  # any view window: the synthetic server has no raw detections

README = """# Synthetic API fixtures (web e2e)

SYNTHETIC data: a tiny invented layer around Cordoba (seeded), NOT real FIRMS counts. Never show these numbers
as real. Generated by `backend/scripts/web_fixtures.py` through the real FastAPI app; do not edit by hand.
`backend/tests/test_web_fixtures.py` fails when these files differ from a fresh run.

`index.json` maps a canonical request key to a file; see `web/e2e/api.ts` for the key format. `responses`
holds status and headers per file (default: 200 JSON). `/cells` files hold `{"months": {YYYY-MM: answer}}` for
every month of the period for the Cordoba VIIRS-eq series (the calendar clicks any month) and the months the
specs request (`KEY_MONTHS`) for the rest, one file per area + scale: the request key has `month=*` and
`api.ts` picks the
month entry (`/stats` with `ref` works the same, `ref=*`, for the Cordoba preset). The view window `bbox` is
not part of the key, so each answer holds every cell of the area.
`/calendar` answers carry the `enso` block built from a SYNTHETIC ONI (`ONI_RUNS`, all three phases).
`/detections` answers 404 for every month: the synthetic server has no raw detections.
A polygon request (any vertices) maps to the one polygon fixture.
`index-inspector.json` adds the chosen-month stats (`ref`) and the `/export.csv` answers (status and
headers per file in `responses`); `export-detections-available.csv` is the answer of a server that has
raw detections.
"""


def request_key(path: str, body: dict) -> str:
    """Canonical key of a request; must match `requestKey` in web/e2e/api.ts."""
    if "preset" in body:
        area = f"preset:{body['preset']}"
    elif body["area"]["type"] == "circle":
        a = body["area"]
        area = f"circle:{a['lat']:.2f},{a['lon']:.2f},{a['radius_km']:g}"
    else:
        area = "polygon"
    parts = [f"POST {path}", f"area={area}", f"scale={body.get('scale', 'viirs_eq')}"]
    for k in ("month", "start", "end", "ref", "kind"):
        if body.get(k):
            parts.append(f"{k}={body[k]}")
    return " ".join(parts)


def synthetic_rows(years=YEARS) -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    cells = [(la, lo) for la in GRID_LAT for lo in GRID_LON] + list(EXTRA)
    rows = []
    for year in years:
        for month in range(1, 13):
            season = 1.0 + 3.0 * np.exp(-(((month - 9) % 12) ** 2) / 6.0)  # peak around September
            trend = 1.0 + 0.05 * (year - years[0])
            for i, (la, lo) in enumerate(cells):
                n = int(rng.poisson(0.6 * season * trend * (1.5 if i % 3 == 0 else 0.7)))
                if n == 0 and i != 0:
                    continue
                n = max(n, 1) if i == 0 else n  # every month keeps at least one row (sensor availability)
                viirs = year >= VIIRS_FIRST_YEAR
                # SYNTHETIC status: the last two months of the last year are NRT (provisional), the rest of that
                # year is API standard processing, MODIS drift covers the last year, earlier years are country SP.
                last = year == years[-1]
                prov = last and month >= 11
                level = "nrt" if prov else ("api-sp" if last else "country-sp")
                vrep = float(rng.poisson(n * 1.8)) if viirs else np.nan
                rows.append(
                    {
                        "year": year, "month": month, "cell_id": int(abs(la) * 1000 + abs(lo) * 10),
                        "cell_lat": la, "cell_lon": lo,
                        "modis_reported": float(n), "viirs_reported": vrep,
                        "modis_eq": float(n), "viirs_eq": vrep if viirs else round(n * 1.8, 3),
                        "modis_eq_estimated": False, "viirs_eq_estimated": not viirs,
                        "modis_sats": "terra", "viirs_source": "snpp" if viirs else "",
                        "method": "synthetic", "calibration_version": "synthetic-1",
                        "provisional": prov, "source_level": level, "source_levels": level, "modis_drift": last,
                    }
                )  # fmt: skip
    return pd.DataFrame(rows)


def bands(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    est = df[df["viirs_eq_estimated"]].copy()
    est["block"] = block_ids(est["cell_lat"].to_numpy(), est["cell_lon"].to_numpy())
    common = {"target": "viirs_eq", "nominal": 0.8}
    m = est.groupby(["year", "month", "block"], as_index=False)["viirs_eq"].sum()
    y = est.groupby(["year", "block"], as_index=False)["viirs_eq"].sum()
    out = []
    for g in (m, y):
        g = g.rename(columns={"viirs_eq": "estimate"})
        g["lo"], g["hi"] = (g["estimate"] * 0.7).round(3), (g["estimate"] * 1.4).round(3)
        out.append(g.assign(**common))
    return out[0], out[1]


def build_layer(processed: Path, years=YEARS) -> None:
    root = processed / "harmonized"
    df = synthetic_rows(years)
    (root / "series").mkdir(parents=True)
    for year, g in df.groupby("year"):
        g.to_parquet(root / "series" / f"{year}.parquet")
    month, year = bands(df)
    for name, b in (("band_block_month", month), ("band_block_year", year)):
        (root / name).mkdir()
        for y, g in b.groupby("year"):
            g.to_parquet(root / name / f"{y}.parquet")
    manifest = LayerManifest(
        id="harmonized", title="Harmonized fire series (SYNTHETIC)", kind="series", source=SOURCE,
        period=f"{years[0]}-01-01/{years[-1]}-12-31", license="synthetic, no real data",
        updated_at=datetime(2026, 1, 1, tzinfo=UTC),
        files=[f"series/{y}.parquet" for y in sorted(df["year"].unique())],
        method="synthetic", calibration_version="synthetic-1",
        notes={
            "es": ["Datos sintéticos de prueba: no son focos reales."],
            "en": ["Synthetic test data: not real hot spots."],
        },
    )  # fmt: skip
    (root / "manifest.json").write_text(manifest.model_dump_json())


# SYNTHETIC ONI runs (first month, last month, ONI): long enough for the CPC rule (>= 5 months), so the
# phases come out of `classify_phase`. Everything else is neutral (0.0). Not real ONI values.
ONI_RUNS = (
    ("2006-08", "2007-02", 1.1),  # El Nino
    ("2007-07", "2008-05", -1.3),  # La Nina
    ("2009-07", "2010-03", 1.4),  # El Nino
    ("2010-06", "2011-04", -1.5),  # La Nina
    ("2014-10", "2016-05", 1.6),  # El Nino
    ("2016-08", "2017-02", -0.8),  # La Nina, runs past the fixture period
)
ONI_RANGE = ("2004-01", "2017-12")  # wider than the fixture period: months outside it must be dropped


def build_enso(path: Path) -> None:
    """A SYNTHETIC monthly ONI table (date, season, oni, above_threshold, phase) with all three phases."""
    idx = pd.date_range(f"{ONI_RANGE[0]}-01", f"{ONI_RANGE[1]}-01", freq="MS")
    oni = pd.Series(0.0, index=idx)
    for first, last, value in ONI_RUNS:
        oni[f"{first}-01" : f"{last}-01"] = value
    df = pd.DataFrame({"date": idx, "season": "SYN", "oni": oni.to_numpy()})
    df["above_threshold"] = enso.above_threshold(oni).to_numpy()
    df["phase"] = enso.classify_phase(oni).to_numpy()
    assert {"nino", "nina", "neutral"} <= set(df["phase"]), "the synthetic ONI must show all three phases"
    enso.write_enso(df, path)


def dump(obj) -> str:
    return json.dumps(obj, sort_keys=True, indent=1, ensure_ascii=False) + "\n"


# --- Inspector and downloads (SA4.5, SA4.6): chosen months and CSV exports ------------------------
INSPECTOR_INDEX = "index-inspector.json"
# Response headers of /export.csv that the web uses or that document the provenance.
EXPORT_HEADERS = ("content-disposition", "x-firecal-source", "x-firecal-period", "x-firecal-calibration")
AVAILABLE_DETECTIONS = "export-detections-available.csv"
DETECTIONS_ROWS = [  # SYNTHETIC points inside the Cordoba preset; they pass the phase-1 filters
    ("2015-09-03T17:40:00", "2015-09-03", "VIIRS", "N", "375m", "D", -31.5, -64.2, None, "nominal", 12.5),
    ("2015-09-04T06:05:00", "2015-09-04", "MODIS", "Terra", "MCD14ML", "N", -32.1, -63.9, 70.0, "", 30.1),
]  # fmt: skip


def build_detections(root: Path) -> None:
    """A tiny synthetic raw-detections tree in the layout `export._detections` reads."""
    cols = ["acq_datetime", "acq_date", "sensor", "satellite", "product", "daynight", "latitude", "longitude",
            "confidence_pct", "confidence_class", "frp"]  # fmt: skip
    df = pd.DataFrame(DETECTIONS_ROWS, columns=cols)
    df["acq_datetime"] = pd.to_datetime(df["acq_datetime"])
    df["acq_date"] = pd.to_datetime(df["acq_date"]).dt.date
    df["type"] = 0
    df["version"] = "synthetic"
    for product, g in df.groupby("product"):
        folder = root / f"product={product}" / "year=2015"
        folder.mkdir(parents=True)
        g.to_parquet(folder / "part-0.parquet")


def inspector_fixtures(client: TestClient, detections_client: TestClient, out: Path) -> dict:
    """Stats for chosen months and the CSV exports; returns the content of `index-inspector.json`."""
    requests: dict[str, str] = {}
    responses: dict[str, dict] = {}

    def keep(path: str, body: dict, name: str, resp, in_index: bool = True, payload=None) -> None:
        if payload is not None:  # several answers in one file (see the README)
            (out / name).write_text(dump(payload))
            requests[request_key(path, body)] = name
            responses[name] = {"status": 200, "headers": {}}
            return
        is_csv = resp.headers["content-type"].startswith("text/csv")
        (out / name).write_text(resp.text if is_csv else dump(resp.json()))
        if in_index:
            requests[request_key(path, body)] = name
        headers = {h: resp.headers[h] for h in EXPORT_HEADERS if h in resp.headers}
        responses[name] = {"status": resp.status_code, "headers": headers}

    for scale in SCALES:  # /stats for every chosen month (`ref`), one file per scale
        refs: dict[str, dict] = {}
        for ref in months_for("cordoba", scale):
            r = client.post("/stats", json={**AREAS["cordoba"], "scale": scale, "ref": ref})
            r.raise_for_status()
            refs[ref] = r.json()
        body = {**AREAS["cordoba"], "scale": scale, "ref": "*"}
        keep("/stats", body, f"stats-cordoba-{scale}-months.json", None, payload={"months": refs})
    body = {**AREAS["cordoba"], "scale": "viirs_eq", "kind": "calendar"}
    keep("/export.csv", body, "export-calendar-cordoba-viirs_eq.csv", client.post("/export.csv", json=body))
    # No raw detections on this server: the answer is 404 and the web hides the hot-spot download.
    body = {**AREAS["cordoba"], "scale": "viirs_eq", "kind": "detections"}
    keep(
        "/export.csv", body, "export-detections-cordoba-viirs_eq.json", client.post("/export.csv", json=body)
    )
    r = detections_client.post("/export.csv", json=body)
    r.raise_for_status()
    keep("/export.csv", body, AVAILABLE_DETECTIONS, r, in_index=False)
    return {
        "synthetic": True,
        "note": "SYNTHETIC data, not real FIRMS counts. `responses` holds status and headers per file.",
        "requests": requests,
        "responses": responses,
    }


def generate(out: Path) -> list[str]:
    """Write the fixtures into `out`; return the file names written."""
    out.mkdir(parents=True, exist_ok=True)
    index: dict[str, str] = {}
    responses: dict[str, dict] = {DETECTIONS_404: {"status": 404, "headers": {}}}
    with tempfile.TemporaryDirectory() as tmp:
        build_layer(Path(tmp))
        oni = Path(tmp) / "enso" / "oni_monthly.parquet"
        build_enso(oni)
        client = TestClient(
            create_app(processed_dir=Path(tmp), detections_dir=Path(tmp) / "none", enso_path=oni)
        )
        build_detections(Path(tmp) / "detections")
        with_detections = TestClient(
            create_app(processed_dir=Path(tmp), detections_dir=Path(tmp) / "detections", enso_path=oni)
        )
        for area_name, area_body in AREAS.items():
            for scale in SCALES:
                for path in PATHS:
                    body = {**area_body, "scale": scale}
                    resp = client.post(path, json=body)
                    resp.raise_for_status()
                    name = f"{path.strip('/')}-{area_name}-{scale}.json"
                    (out / name).write_text(dump(resp.json()))
                    index[request_key(path, body)] = name
                # /cells for EVERY month of the period, from the real app, in one file per area + scale.
                months: dict[str, dict] = {}
                for month in months_for(area_name, scale):
                    body = {**area_body, "scale": scale, "month": month}
                    resp = client.post("/cells", json=body)
                    resp.raise_for_status()
                    months[month] = resp.json()
                    det = client.post("/detections", json={**body, "bbox": DET_BBOX})
                    assert det.status_code == 404, det.text
                    detections_404 = det.json()
                name = f"cells-{area_name}-{scale}.json"
                (out / name).write_text(dump({"months": months}))
                index[request_key("/cells", {**area_body, "scale": scale, "month": "*"})] = name
                (out / DETECTIONS_404).write_text(dump(detections_404))
                index[request_key("/detections", {**area_body, "scale": scale, "month": "*"})] = (
                    DETECTIONS_404
                )
        extra = inspector_fixtures(client, with_detections, out)
    (out / INSPECTOR_INDEX).write_text(dump(extra))
    (out / "index.json").write_text(
        dump(
            {
                "synthetic": True,
                "note": "SYNTHETIC data, not real FIRMS counts",
                "requests": index,
                "responses": responses,
            }
        )
    )
    (out / "README.md").write_text(README)
    return sorted({*index.values(), *extra["responses"], INSPECTOR_INDEX, "index.json", "README.md"})


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DEFAULT
    print("\n".join(generate(target)))
