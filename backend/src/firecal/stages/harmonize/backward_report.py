"""Markdown report SA2.8 (backward validation and the P4 condition 2 gate); every number comes from code."""

import datetime as dt

import pandas as pd

from firecal.stages.harmonize.backward import CI, N_BOOT, SEED, TEST_YEARS, TRAIN_FIRST, TRAIN_LAST
from firecal.stages.harmonize.evaluate import PAIRS
from firecal.stages.harmonize.report import md_table, num, pct

SRC = "monthly region cube from the 0.1 degree grid (default filters), 2.5 degree blocks; code `harmonize/backward.py` and `evaluate.py`"


def _fmt_ym(ym: int) -> str:
    return f"{ym // 12}-{ym % 12 + 1:02d}"


def _scores_section(res: dict, label: str) -> list[str]:
    s: pd.DataFrame = res["scores"]
    out = [f"#### {label}", ""]
    rows = []
    for year in [*TEST_YEARS, "all"]:
        for level in ("block-month", "block-year"):
            for scheme, name in (
                ("backward_with", "with drift years"),
                ("backward_without", "without drift years"),
            ):
                m = s[(s["scheme"] == scheme) & (s["test_year"] == year) & (s["level"] == level)]
                if m.empty:
                    continue
                r = m.iloc[0]
                rows.append(
                    [
                        year if year != "all" else "pooled",
                        level,
                        name,
                        pct(r["wape"]),
                        pct(r["bias"], True),
                        num(r["mae"], 2),
                        num(r["deviance"], 3),
                        int(r["n"]),
                    ]
                )
    out += md_table(
        ["Test year", "Level", "Training", "WAPE", "Relative bias", "MAE", "Poisson deviance", "Rows"], rows
    )
    return out + [""]


def _pair_section(key: str, res: dict, window: str) -> list[str]:
    pair = res["pair"]
    rw, ro = res["with"], res["without"]
    b = res["boot"]
    out = [
        f"### {key}: {PAIRS[pair].label}",
        "",
        f"Drift years dropped from training in the 'without' fit: {window}. Training months: with {len(rw.train_ym)} ({_fmt_ym(int(rw.train_ym.min()))}..{_fmt_ym(int(rw.train_ym.max()))}), "
        f"without {len(ro.train_ym)}. `k` selected inside the training set: with {rw.k:g}{' (fallback)' if rw.k_fallback else ''}, without {ro.k:g}{' (fallback)' if ro.k_fallback else ''}.",
        "",
    ]
    if not res["drop_years"]:
        out += ["No drift years under this rule: the two fits are identical and the gate cannot be met.", ""]
    out += _scores_section(res, "Error per test year (all blocks)")
    out += [
        "Paired bootstrap of the pooled block-year differences (without - with; negative = better without drift years):",
        "",
    ]
    out += md_table(
        [
            "Metric",
            "Pooled with",
            "Pooled without",
            "Difference (point estimate, percentage points)",
            f"{CI[1] - CI[0]:.0f} % interval",
            "Interval entirely < 0",
        ],
        [
            [
                "WAPE (block-year)",
                pct(res["wape_with"]),
                pct(res["wape_without"]),
                pct(b["wape_diff"], True),
                f"[{pct(b['wape_lo'], True)}, {pct(b['wape_hi'], True)}]",
                "yes" if b["wape_hi"] < 0 else "no",
            ],
            [
                "abs(relative bias)",
                pct(res["bias_with"]),
                pct(res["bias_without"]),
                pct(b["bias_diff"], True),
                f"[{pct(b['bias_lo'], True)}, {pct(b['bias_hi'], True)}]",
                "yes" if b["bias_hi"] < 0 else "no",
            ],
        ],
    )
    not_worse = b["wape_diff"] <= 0 and b["bias_diff"] <= 0
    out += [
        "",
        f"Gate (P4 condition 2): neither metric worse (point differences <= 0): {'yes' if not_worse else 'no'}; at least one with its interval entirely < 0: {'yes' if (b['wape_hi'] < 0 or b['bias_hi'] < 0) else 'no'}. "
        f"Valid bootstrap resamples: {int(b['n_boot'])} of {N_BOOT}.",
        "",
        f"**Verdict {key}: {res['verdict']}.**",
        "",
    ]
    return out


def build_sa28_report(results: dict[str, dict], windows: dict[str, str], run_date: dt.date) -> str:
    """`results`: key -> run_pair() output (plus pooled numbers); `windows`: key -> readable window label."""
    out = [
        "# SA2.8: backward validation (train 2016+, test 2012-2015)",
        "",
        f"Generated by `firecal harmonize backward` on {run_date.isoformat()}. All numbers come from code. Source: {SRC}.",
        "",
        f"Design (P4 condition 2 and Revision 1): the SA2.2 factor (`k` selected by the inner leave-one-year-out inside the training set) is trained on {_fmt_ym(TRAIN_FIRST)}..{_fmt_ym(TRAIN_LAST)} with no gap and tested on each year {TEST_YEARS[0]}..{TEST_YEARS[-1]} "
        "(2012 from 2012-02, the partial month 2012-01 is out). Every pair is trained twice: with all training months and without the drift years of that pair (P3 epochs; Terra only for `terra_to_viirs`). "
        f"Paired bootstrap: years and blocks resampled separately, {N_BOOT} resamples, seed {SEED}, {CI[1] - CI[0]:.0f} % percentile interval, on the pooled block-year WAPE and pooled |relative bias| (without - with). "
        "The gate is met only if neither metric is worse (point difference <= 0) and at least one has its interval entirely < 0. With only four test years the year resampling is coarse: read the intervals accordingly.",
        "",
        "Whatever the verdict, `sf-2026.11.2` keeps the `sf-2026.11.1` pairs unchanged; a recalibration, if warranted, would go to a later version with its own report. "
        'Observed MODIS in drift years stays flagged "orbit drift (unverified cause)" in any case. This is a retrospective test of the relationship over time, not an alert.',
        "",
        "## Verdict summary",
        "",
    ]
    out += md_table(
        [
            "Pair / window",
            "Drift years dropped",
            "WAPE diff (95 % interval)",
            "abs(bias) diff (95 % interval)",
            "Verdict",
        ],
        [
            [
                k,
                windows[k],
                f"{pct(r['boot']['wape_diff'], True)} [{pct(r['boot']['wape_lo'], True)}, {pct(r['boot']['wape_hi'], True)}]",
                f"{pct(r['boot']['bias_diff'], True)} [{pct(r['boot']['bias_lo'], True)}, {pct(r['boot']['bias_hi'], True)}]",
                r["verdict"],
            ]
            for k, r in results.items()
        ],
    )
    out += ["", "## Per pair", ""]
    for k, r in results.items():
        out += _pair_section(k, r, windows[k])
    return "\n".join(out) + "\n"
